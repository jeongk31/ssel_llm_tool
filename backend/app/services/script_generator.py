def code_dataframe(df: pd.DataFrame) -> pd.DataFrame:
    """Code every row in the DataFrame using the LLM."""
    results = []
    total = len(df)

    kept_index = []

    for idx, row in df.iterrows():
        message = "" if pd.isna(row[MESSAGE_COLUMN]) else str(row[MESSAGE_COLUMN])
        if message.strip() == "":
            if EMPTY_MESSAGE_HANDLING == "ignore":
                print(f"  [{{idx + 1}}/{{total}}] Skipping empty row (ignored)")
                continue  # drop the row entirely
            elif EMPTY_MESSAGE_HANDLING == "code":
                print(f"  [{{idx + 1}}/{{total}}] Coding empty row from codebook")
                result = call_llm(build_prompt(message, row))
            else:
                print(f"  [{{idx + 1}}/{{total}}] Empty row -> null")
                result = {{{", ".join(f'{json.dumps(l)}: None' for l in labels)}}}
                result["_error"] = "empty_message"
        else:
            print(f"  [{{idx + 1}}/{{total}}] Coding: {{message[:80]}}...")
            result = call_llm(build_prompt(message, row))

        result["_raw_response"] = json.dumps(result)
        results.append(result)
        kept_index.append(idx)

    # Add coded columns to the (kept) rows.
    result_df = df.loc[kept_index].copy()
    for label in CODEBOOK_LABELS:
        result_df[label] = [r.get(label) for r in results]
    result_df["_raw_response"] = [r.get("_raw_response", "") for r in results]
    result_df["_error"] = [r.get("_error", "") for r in results]

    return result_df


