def load_dataset(file_path: str) -> pd.DataFrame:
    """Load CSV or Excel file into a DataFrame."""
    ext = file_path.rsplit(".", 1)[-1].lower()
    if ext == "csv":
        df = pd.read_csv(file_path)
    elif ext in ("xlsx", "xls"):
        df = pd.read_excel(file_path)
    else:
        raise ValueError(f"Unsupported file type: .{{ext}}")

    if MESSAGE_COLUMN not in df.columns:
        raise ValueError(
            f"Column '{{MESSAGE_COLUMN}}' not found. "
            f"Available columns: {{list(df.columns)}}"
        )
    return df


def group_units(df: pd.DataFrame) -> pd.DataFrame:
    """Collapse rows sharing an identifier combination into one tagged unit."""
    id_cols = [c for c in IDENTIFIER_COLUMNS if c in df.columns]
    if not id_cols:
        return df

    context_columns = [
        spec.get("column") for spec in CONTEXT
        if spec.get("column") and spec.get("column") in df.columns
    ]
    conflicts = []
    for context_column in context_columns:
        count = 0
        for _, group in df.groupby(id_cols, sort=False, dropna=False):
            keys = set()
            for value in group[context_column].tolist():
                if pd.isna(value):
                    keys.add(("missing", None))
                else:
                    keys.add((type(value).__name__, str(value)))
            if len(keys) > 1:
                count += 1
        if count:
            conflicts.append(f"{{context_column}} ({{count}} episode(s))")
    if conflicts:
        raise ValueError(
            "Selected Context fields must contain exactly one value within every "
            "episode: " + ", ".join(conflicts)
        )

    work = df.copy()
    if ORDER_COLUMN and ORDER_COLUMN in work.columns:
        work = work.sort_values(
            by=ORDER_COLUMN,
            ascending=(ORDER_DIRECTION != "desc"),
            kind="stable",
        )

    use_identity = bool(IDENTITY_COLUMN) and IDENTITY_COLUMN in work.columns
    units = []
    for _, group in work.groupby(id_cols, sort=False, dropna=False):
        parts = []
        for _, r in group.iterrows():
            msg = "" if pd.isna(r[MESSAGE_COLUMN]) else str(r[MESSAGE_COLUMN])
            who = r[IDENTITY_COLUMN] if use_identity else None
            if use_identity and pd.notna(who) and str(who).strip() != "":
                parts.append(f"[{{who}}] {{msg}}")
            else:
                parts.append(msg)
        unit = group.iloc[0].to_dict()
        unit[MESSAGE_COLUMN] = "\\n".join(parts)
        units.append(unit)

    return pd.DataFrame(units, columns=list(df.columns)).reset_index(drop=True)


def load_package_csvs(episode_path: str):
    """Load and validate CAT's canonical three-CSV package input."""
    package_dir = os.path.dirname(os.path.abspath(episode_path))
    expected_episode_path = os.path.join(package_dir, PACKAGE_EPISODE_FILE)
    source_path = os.path.join(package_dir, PACKAGE_SOURCE_FILE)
    row_map_path = os.path.join(package_dir, PACKAGE_ROW_MAP_FILE)
    missing_files = [
        os.path.basename(path)
        for path in (source_path, expected_episode_path, row_map_path)
        if not os.path.isfile(path)
    ]
    if missing_files:
        raise ValueError(f"The coding package is missing required CSV files: {{missing_files}}")

    source_df = pd.read_csv(source_path)
    episode_df = pd.read_csv(expected_episode_path)
    row_map = pd.read_csv(row_map_path)

    if MESSAGE_COLUMN not in episode_df.columns:
        raise ValueError(
            f"Column '{{MESSAGE_COLUMN}}' was not found in {{PACKAGE_EPISODE_FILE}}. "
            f"Available columns: {{list(episode_df.columns)}}"
        )

    required_map_columns = ["source_row", "episode"]
    missing_map_columns = [c for c in required_map_columns if c not in row_map.columns]
    if missing_map_columns:
        raise ValueError(f"{{PACKAGE_ROW_MAP_FILE}} is missing required columns: {{missing_map_columns}}")

    row_map = row_map.loc[:, required_map_columns].copy()
    for column in required_map_columns:
        try:
            numeric = pd.to_numeric(row_map[column], errors="raise")
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Row-map column '{{column}}' must contain integers.") from exc
        if not numeric.map(lambda value: float(value).is_integer()).all():
            raise ValueError(f"Row-map column '{{column}}' must contain integers.")
        row_map[column] = numeric.astype(int)

    expected_source_rows = list(range(1, len(source_df) + 1))
    if sorted(row_map["source_row"].tolist()) != expected_source_rows:
        raise ValueError(
            "Row-map source_row values must contain each one-based source-row "
            "position exactly once."
        )
    if not row_map.empty and (
        (row_map["episode"] < 1) | (row_map["episode"] > len(episode_df))
    ).any():
        raise ValueError("Row-map episode values fall outside episodes.csv.")

    return source_df, episode_df, row_map


def validate_sender_data(source_df: pd.DataFrame):
    """Verify that embedded sender output keys still match the packaged data."""
    if not any(entry.get("level") == "sender" for entry in CODEBOOK):
        return
    if not IDENTITY_COLUMN or IDENTITY_COLUMN not in source_df.columns:
        # Package mode intentionally omits IDENTITY_COLUMN because episodes are
        # already constructed, so use the compact sender column when available.
        candidate = next((column for column in COMPACT_COLUMNS if column in source_df.columns and column.lower() in ("sender", "speaker", "identity")), None)
        if not candidate:
            return
        sender_column = candidate
    else:
        sender_column = IDENTITY_COLUMN
    detected = []
    seen = set()
    blank_rows = []
    for position, value in enumerate(source_df[sender_column].tolist(), start=1):
        if pd.isna(value) or str(value).strip() == "":
            blank_rows.append(position)
            continue
        name = str(value).strip()
        if name not in seen:
            seen.add(name)
            detected.append(name)
    if blank_rows:
        raise ValueError(
            f"Sender column '{{sender_column}}' contains blank values in source rows: "
            + ", ".join(str(value) for value in blank_rows[:5])
        )
    if detected != PARTICIPANTS:
        raise ValueError(
            "Detected sender names no longer match the verified package configuration. "
            f"Expected {{PARTICIPANTS}}; found {{detected}}."
        )


def resolve_code_columns(source_columns, compact_columns):
    """Choose collision-safe output names once for both package outputs."""
    if len(set(CODEBOOK_LABELS)) != len(CODEBOOK_LABELS):
        raise ValueError("Codebook output labels must be unique.")

    used = {{str(column) for column in source_columns}}
    used.update(str(column) for column in compact_columns)
    resolved = {{}}
    for label in CODEBOOK_LABELS:
        candidate = label
        if candidate in used:
            candidate = f"{{label}}_coded"
            suffix = 2
            while candidate in used:
                candidate = f"{{label}}_coded_{{suffix}}"
                suffix += 1
        resolved[label] = candidate
        used.add(candidate)
    return resolved


def code_package_episodes(episode_df: pd.DataFrame) -> pd.DataFrame:
    """Code canonical episodes while retaining one result row per episode."""
    results = []
    total = len(episode_df)
    null_result = {{label: None for label in CODEBOOK_LABELS}}

    for position, (_, row) in enumerate(episode_df.iterrows(), start=1):
        message = "" if pd.isna(row[MESSAGE_COLUMN]) else str(row[MESSAGE_COLUMN])
        if message.strip() == "":
            if EMPTY_MESSAGE_HANDLING == "ignore":
                print(f"  [{{position}}/{{total}}] Skipping empty episode (codes left blank)")
                result = null_result.copy()
            elif EMPTY_MESSAGE_HANDLING == "code":
                print(f"  [{{position}}/{{total}}] Coding empty episode from codebook")
                result = call_llm(build_prompt(message, row))
            else:
                print(f"  [{{position}}/{{total}}] Empty episode -> blank codes")
                result = null_result.copy()
        else:
            print(f"  [{{position}}/{{total}}] Coding: {{message[:80]}}...")
            result = call_llm(build_prompt(message, row))

        results.append({{label: result.get(label) for label in CODEBOOK_LABELS}})

    return pd.DataFrame(results, columns=CODEBOOK_LABELS)


def build_package_results(
    source_df: pd.DataFrame,
    episode_df: pd.DataFrame,
    row_map: pd.DataFrame,
    episode_codes: pd.DataFrame,
):
    """Build source-row primary and compact episode-level result frames."""
    if len(episode_codes) != len(episode_df):
        raise ValueError("Episode-code count does not match the episode sheet.")
    if len(set(COMPACT_COLUMNS)) != len(COMPACT_COLUMNS):
        raise ValueError("Compact output columns must be unique.")
    missing_compact = [column for column in COMPACT_COLUMNS if column not in episode_df.columns]
    if missing_compact:
        raise ValueError(f"Episode sheet is missing compact columns: {{missing_compact}}")

    code_columns = resolve_code_columns(source_df.columns, COMPACT_COLUMNS)
    for label, output_column in code_columns.items():
        if output_column != label:
            print(f"  Output column '{{label}}' renamed to '{{output_column}}' to preserve source data")

    ordered_map = row_map.set_index("source_row").reindex(range(1, len(source_df) + 1))
    episode_positions = ordered_map["episode"].astype(int).to_numpy() - 1
    expanded_codes = episode_codes.iloc[episode_positions].reset_index(drop=True)

    primary_df = source_df.copy()
    for label in CODEBOOK_LABELS:
        primary_df[code_columns[label]] = expanded_codes[label].tolist()

    compact_df = episode_df.loc[:, COMPACT_COLUMNS].copy()
    for label in CODEBOOK_LABELS:
        compact_df[code_columns[label]] = episode_codes[label].tolist()

    return primary_df, compact_df


def save_package_results(
    primary_df: pd.DataFrame,
    compact_df: pd.DataFrame,
    input_path: str,
    also_save_episodes: bool,
):
    """Write the package's primary CSV and optional compact CSV."""
    output_dir = os.path.dirname(os.path.abspath(input_path))
    primary_path = os.path.join(output_dir, f"{{RESULT_STEM}}_coded.csv")
    primary_df.to_csv(primary_path, index=False)

    compact_path = None
    if also_save_episodes:
        compact_path = os.path.join(output_dir, f"{{RESULT_STEM}}_coded_episodes.csv")
        compact_df.to_csv(compact_path, index=False)
    return primary_path, compact_path


def build_prompt(message_text: str, row=None) -> str:
    """Construct the full prompt for coding one row."""
    context_section = ""
    if CONTEXT and row is not None:
        lines = []
        for spec in CONTEXT:
            col = spec.get("column")
            if not col or col not in row:
                continue
            val = row[col]
            if pd.isna(val) or str(val).strip() == "":
                continue
            desc = (spec.get("description") or "").strip()
            lines.append(f"- {{col}}: {{val}}" + (f"  ({{desc}})" if desc else ""))
        if lines:
            context_section = "\\n## Context\\n" + "\\n".join(lines) + "\\n"

    coding_section = f"\\n## Coding Instructions\\n{{CODING_INSTRUCTIONS}}\\n" if CODING_INSTRUCTIONS.strip() else ""

    prompt = f"""You are coding one row of data. One row = one episode of observation.

## Experiment Instructions
{{EXPERIMENT_INSTRUCTIONS}}
{{coding_section}}
## Codebook
{{CODEBOOK_PROMPT_BLOCK}}
{{context_section}}
## Message to Code
{{message_text}}

## Output Requirements
- Return ONLY valid JSON
- Keys must exactly match: {{CODEBOOK_LABELS}}
- Each value must conform to the type and allowed values specified above
- Do not include any commentary, explanation, or markdown formatting
"""
    return prompt


